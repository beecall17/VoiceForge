"""
Day 9 (part 1): Split data/dpo_pairs.jsonl into train/val and push to the
Hub as a dataset, so the DPO training notebook loads from there instead
of depending on local files.

No separate test split here -- Day 10's evaluation reuses the SFT
dataset's existing `test` split (same held-out briefs, so SFT-only vs
SFT+DPO outputs are directly comparable on prompts neither model trained
on).

Requires a Hugging Face token with write access, same as Day 4:
  HF_TOKEN=hf_... (in .env)

Usage (run from the voiceforge/ repo root):
  python scripts/push_dpo_dataset_to_hub.py --repo_id your-username/voiceforge-brand-voice-dpo
"""

import argparse
import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()
import os


def load_jsonl(path):
    return [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]


def stratified_train_val_split(rows, val_frac=0.1, seed=42):
    """Split independently within each `voice` group, same rationale as
    Day 4's split: keep both personas balanced across train/val, not just
    balanced in the pooled dataset."""
    rng = random.Random(seed)
    by_voice = defaultdict(list)
    for r in rows:
        by_voice[r["voice"]].append(r)

    train, val = [], []
    for voice, group in by_voice.items():
        group = group[:]
        rng.shuffle(group)
        n_val = max(1, int(len(group) * val_frac))
        val.extend(group[:n_val])
        train.extend(group[n_val:])

    rng.shuffle(train)
    rng.shuffle(val)
    return train, val


def build_dataset_card(repo_id, splits, sft_dataset_repo):
    def counts(rows):
        voice = dict(Counter(r["voice"] for r in rows))
        method = dict(Counter(r["label_method"] for r in rows))
        return voice, method

    lines = [
        "# VoiceForge Brand-Voice DPO Preference Dataset",
        "",
        "Preference pairs (`prompt` / `chosen` / `rejected`) for DPO alignment",
        "of the VoiceForge brand-voice SFT model, continuing from",
        f"`{sft_dataset_repo}`. Candidates were generated by the SFT model at",
        "two sampling temperatures (0.6 / 1.2), then labeled in two tiers:",
        "rule-based (banned-phrase/CTA/length checks -- only accepted when the",
        "winner has zero violations) first, falling back to an LLM judge",
        "scored against the persona voice-guide rubric only when both",
        "candidates pass the rule-based checks. Near-identical pairs and",
        "pairs where both candidates were flawed were discarded rather than",
        "forced into a label.",
        "",
        "## Splits",
        "",
        "| Split | Rows | Voice balance | Label method |",
        "|---|---|---|---|",
    ]
    for name, rows in splits.items():
        v, m = counts(rows)
        lines.append(f"| {name} | {len(rows)} | {v} | {m} |")

    lines += [
        "",
        "## Source",
        "- SFT model / base dataset: "
        f"[{sft_dataset_repo}](https://huggingface.co/datasets/{sft_dataset_repo})",
        "- Pipeline: `scripts/generate_dpo_candidates` (notebook) -> "
        "`scripts/label_dpo_pairs.py` -> `scripts/push_dpo_dataset_to_hub.py`",
        "",
        "## Intended use",
        "Educational / portfolio DPO fine-tuning project. Not vetted for",
        "production marketing use without further review.",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo_id", required=True, help="e.g. your-username/voiceforge-brand-voice-dpo")
    ap.add_argument("--pairs", default="data/dpo_pairs.jsonl")
    ap.add_argument("--sft_dataset_repo", default="bikalpoudel/voiceforge-brand-voice-sft")
    ap.add_argument("--val_frac", type=float, default=0.1)
    ap.add_argument("--private", action="store_true")
    ap.add_argument("--dry_run", action="store_true")
    args = ap.parse_args()

    if not args.dry_run and "HF_TOKEN" not in os.environ:
        sys.exit("Set HF_TOKEN before running -- either export it or add it to .env.")

    rows = load_jsonl(args.pairs)
    if not rows:
        sys.exit(f"No rows found in {args.pairs} -- did Day 8's labeling script run successfully?")
    print(f"Loaded {len(rows)} labeled pairs from {args.pairs}")
    print("Label method breakdown:", dict(Counter(r["label_method"] for r in rows)))

    train, val = stratified_train_val_split(rows, args.val_frac)
    splits = {"train": train, "validation": val}
    print(f"Split: train={len(train)}, validation={len(val)}")

    from datasets import Dataset, DatasetDict

    keep_cols = ["id", "voice", "voice_tag", "format", "product", "angle",
                 "brief", "chosen", "rejected", "chosen_source", "label_method", "reason"]
    dataset_dict = DatasetDict({
        name: Dataset.from_list([{k: r[k] for k in keep_cols} for r in split_rows])
        for name, split_rows in splits.items()
    })
    print(dataset_dict)

    card_text = build_dataset_card(args.repo_id, splits, args.sft_dataset_repo)
    card_path = Path("data") / "DPO_DATASET_CARD_preview.md"
    card_path.write_text(card_text, encoding="utf-8")
    print(f"\nDataset card preview written to {card_path} -- review before pushing.")

    if args.dry_run:
        print("\n--dry_run set: skipping the actual push_to_hub call.")
        return

    dataset_dict.push_to_hub(args.repo_id, private=args.private)

    from huggingface_hub import HfApi
    HfApi().upload_file(
        path_or_fileobj=str(card_path),
        path_in_repo="README.md",
        repo_id=args.repo_id,
        repo_type="dataset",
    )

    visibility = "private" if args.private else "public"
    print(f"\nPushed {visibility} dataset to https://huggingface.co/datasets/{args.repo_id}")
    print(f'Load it later with: load_dataset("{args.repo_id}")')


if __name__ == "__main__":
    main()
