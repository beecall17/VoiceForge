"""
Day 4 (part 2): Package train/val/test into a Hugging Face Dataset and
push it to the Hub, so Day 5's Colab notebook can `load_dataset(...)`
instead of depending on local files.

Reads: data/train.jsonl, data/val.jsonl, data/test.jsonl (from clean_and_split.py)
Writes: a dataset repo on the Hugging Face Hub.

Each row gets a `messages` field (system/user/assistant) built from the
persona-specific system prompt in voice_guidelines.md, so the dataset is
self-contained and directly usable with trl's SFTTrainer / a tokenizer's
apply_chat_template -- no need to re-parse the guidelines doc at train time.

Requires a Hugging Face token with write access. Put it in your .env:
  HF_TOKEN=hf_...

Install:
  pip install datasets huggingface_hub python-dotenv

Usage (run from the voiceforge/ repo root):
  python scripts/push_dataset_to_hub.py --repo_id your-username/voiceforge-brand-voice-sft
  python scripts/push_dataset_to_hub.py --repo_id your-username/voiceforge-brand-voice-sft --private
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

from dotenv import load_dotenv

load_dotenv()

import os

# reuse the same persona-parsing logic as Day 3, so the system prompt baked
# into each row is identical to what generated the completions in the
# first place -- one source of truth, no drift between the two scripts.
sys.path.insert(0, str(Path(__file__).parent))
from generate_completions import build_system_prompts  # noqa: E402


def load_jsonl(path):
    return [json.loads(l) for l in Path(path).read_text(encoding="utf-8").splitlines() if l.strip()]


def to_messages_row(row, system_prompts):
    system_prompt = system_prompts[row["voice"]]
    return {
        "id": row["id"],
        "voice": row["voice"],
        "voice_tag": row["voice_tag"],
        "format": row["format"],
        "product": row["product"],
        "angle": row["angle"],
        "brief": row["brief"],
        "completion": row["completion"],
        "messages": [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": row["brief"]},
            {"role": "assistant", "content": row["completion"]},
        ],
    }


def build_dataset_card(repo_id, splits, voice_doc_path):
    def counts(rows):
        return dict(Counter(r["voice"] for r in rows)), dict(Counter(r["format"] for r in rows))

    lines = [
        f"# VoiceForge Brand-Voice SFT Dataset",
        "",
        "Synthetic supervised fine-tuning data for a two-voice brand-voice",
        "copywriting assistant (`Cozy Crochet` and `Romantic Floral` micro-artisan",
        "personas). Briefs were generated combinatorially from a fixed set of",
        "content formats, product categories, and campaign angles; completions",
        "were generated by a teacher LLM conditioned on persona-specific voice",
        "guidelines, then automatically quality-checked (banned-phrase, CTA-rule,",
        "and length checks) and manually spot-checked before splitting.",
        "",
        "Each row includes a ready-to-use `messages` field",
        "(system/user/assistant) for direct use with `trl.SFTTrainer` or",
        "`tokenizer.apply_chat_template`, plus the flat `brief`/`completion`",
        "fields for readability.",
        "",
        "## Splits",
        "",
        "| Split | Rows | Voice balance | Format coverage |",
        "|---|---|---|---|",
    ]
    for name, rows in splits.items():
        v, f = counts(rows)
        lines.append(f"| {name} | {len(rows)} | {v} | {f} |")

    lines += [
        "",
        "## Source",
        f"- Voice guidelines: `{voice_doc_path}` (see the project repo for the full spec)",
        "- Generation pipeline: `scripts/generate_briefs.py` -> `scripts/generate_completions.py` "
        "-> `scripts/clean_and_split.py` -> `scripts/push_dataset_to_hub.py`",
        "",
        "## Intended use",
        "Educational / portfolio fine-tuning project (QLoRA SFT + DPO). Not",
        "vetted for production marketing use without further review.",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo_id", required=True, help="e.g. your-username/voiceforge-brand-voice-sft")
    ap.add_argument("--data_dir", default="data")
    ap.add_argument("--voice", default="docs/voice_guidelines.md")
    ap.add_argument("--private", action="store_true")
    ap.add_argument("--dry_run", action="store_true", help="build the dataset locally but skip the actual push")
    args = ap.parse_args()

    if not args.dry_run and "HF_TOKEN" not in os.environ:
        sys.exit("Set HF_TOKEN before running -- either export it or add it to .env (see docstring).")

    from datasets import Dataset, DatasetDict

    voice_doc_text = Path(args.voice).read_text(encoding="utf-8")
    system_prompts = build_system_prompts(voice_doc_text)

    data_dir = Path(args.data_dir)
    split_files = {"train": data_dir / "train.jsonl", "validation": data_dir / "val.jsonl", "test": data_dir / "test.jsonl"}

    raw_splits = {}
    for name, path in split_files.items():
        if not path.exists():
            sys.exit(f"Missing {path} -- run scripts/clean_and_split.py first.")
        raw_splits[name] = load_jsonl(path)

    processed_splits = {
        name: [to_messages_row(r, system_prompts) for r in rows]
        for name, rows in raw_splits.items()
    }

    dataset_dict = DatasetDict({
        name: Dataset.from_list(rows) for name, rows in processed_splits.items()
    })
    print(dataset_dict)

    card_text = build_dataset_card(args.repo_id, processed_splits, args.voice)
    card_path = data_dir / "DATASET_CARD_preview.md"
    card_path.write_text(card_text, encoding="utf-8")
    print(f"\nDataset card preview written to {card_path} -- review it before pushing.")

    if args.dry_run:
        print("\n--dry_run set: skipping the actual push_to_hub call.")
        return

    dataset_dict.push_to_hub(args.repo_id, private=args.private)

    from huggingface_hub import HfApi
    HfApi().upload_file(
        path_or_fileobj=str(card_path),
        path_in_repo="README.md",
        repo_id=args.repo_id,
        repo_type="dataset",
    )

    visibility = "private" if args.private else "public"
    print(f"\nPushed {visibility} dataset to https://huggingface.co/datasets/{args.repo_id}")
    print(f'Load it later with: load_dataset("{args.repo_id}")')


if __name__ == "__main__":
    main()
